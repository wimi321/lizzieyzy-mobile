from __future__ import annotations

import sys
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tool"))

import native_licenses  # noqa: E402


class NativeLicenseCanonicalizationTest(unittest.TestCase):
    def test_acknowledgements_are_stable_across_order_and_whitespace(self) -> None:
        first = (
            "# Acknowledgements\n"
            "This application makes use of the following third party libraries:\n"
            "\n## Beta\n\n"
            "Beta terms" + "   \n"
            "\n## Alpha\n\nAlpha terms\n"
            "\nGenerated by CocoaPods - https://cocoapods.org\n"
        )
        second = (
            "# Acknowledgements\r\n"
            "This application makes use of the following third party libraries:\r\n"
            "\r\n## Alpha\r\n\r\nAlpha terms\r\n"
            "\r\n## Beta\r\n\r\nBeta terms\r\n"
            "\r\nGenerated by CocoaPods - https://cocoapods.org\r\n"
        )

        canonical_first, headings_first = (
            native_licenses.canonical_pod_acknowledgements(first)
        )
        canonical_second, headings_second = (
            native_licenses.canonical_pod_acknowledgements(second)
        )

        self.assertEqual(canonical_first, canonical_second)
        self.assertEqual(headings_first, {"Alpha", "Beta"})
        self.assertEqual(headings_first, headings_second)
        self.assertLess(
            canonical_first.index("## Alpha"), canonical_first.index("## Beta")
        )
        self.assertTrue(
            all(line == line.rstrip() for line in canonical_first.splitlines())
        )

    def test_duplicate_heading_is_rejected(self) -> None:
        content = """# Acknowledgements
This application makes use of the following third party libraries:
## Alpha
First
## Alpha
Second
Generated by CocoaPods - https://cocoapods.org
"""
        with self.assertRaises(native_licenses.sbom.SbomError):
            native_licenses.canonical_pod_acknowledgements(content)

    def test_missing_footer_is_rejected(self) -> None:
        content = """# Acknowledgements
This application makes use of the following third party libraries:
## Alpha
Terms
"""
        with self.assertRaises(native_licenses.sbom.SbomError):
            native_licenses.canonical_pod_acknowledgements(content)


if __name__ == "__main__":
    unittest.main()
