#!/usr/bin/env python3
"""Generate fail-closed CocoaPods and Maven license/notice inventories."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import textwrap
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path
from typing import Any

import sbom


ROOT = Path(__file__).resolve().parents[1]
POLICY = ROOT / "tool" / "native_license_policy.json"
POD_LOCK = ROOT / "ios" / "Podfile.lock"
POD_ACKNOWLEDGEMENTS = (
    ROOT
    / "ios"
    / "Pods"
    / "Target Support Files"
    / "Pods-Runner"
    / "Pods-Runner-acknowledgements.markdown"
)
COCOAPODS_ASSET = ROOT / "assets" / "legal" / "cocoapods_third_party_licenses.txt"
MAVEN_ASSET = ROOT / "assets" / "legal" / "maven_third_party_licenses.txt"
GRADLE_CACHE = Path.home() / ".gradle" / "caches" / "modules-2" / "files-2.1"
GRADLE_VERIFICATION = ROOT / "android" / "gradle" / "verification-metadata.xml"
ARCHIVE_SUFFIXES = {".aar", ".jar"}
METADATA_SUFFIXES = {".module", ".pom"}
LEGAL_NAME = re.compile(
    r"(?:^|/)(?:license|licence|notice|copying|third_party_licenses)"
    r"(?:[._-].*)?$",
    re.IGNORECASE,
)
POD_ACKNOWLEDGEMENTS_HEADER = "# Acknowledgements"
POD_ACKNOWLEDGEMENTS_INTRO = (
    "This application makes use of the following third party libraries:"
)
POD_ACKNOWLEDGEMENTS_FOOTER = "Generated by CocoaPods - https://cocoapods.org"


def fail(message: str) -> None:
    raise sbom.SbomError(message)


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_or_check(output: Path, content: str, check: bool) -> None:
    if check:
        if not output.is_file():
            fail(f"missing generated legal asset: {output.relative_to(ROOT)}")
        reviewed = output.read_text("utf-8")
        if reviewed != content:
            reviewed_lines = reviewed.splitlines()
            generated_lines = content.splitlines()
            difference = "different trailing newline or text encoding"
            for index in range(max(len(reviewed_lines), len(generated_lines))):
                reviewed_line = reviewed_lines[index] if index < len(reviewed_lines) else ""
                generated_line = (
                    generated_lines[index] if index < len(generated_lines) else ""
                )
                if reviewed_line != generated_line:
                    difference = (
                        f"first difference at line {index + 1}: "
                        f"reviewed={reviewed_line[:120]!r}, "
                        f"generated={generated_line[:120]!r}"
                    )
                    break
            fail(
                f"generated legal asset is stale: {output.relative_to(ROOT)}; "
                f"regenerate it from the locked native graph; {difference}"
            )
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, "utf-8")


def canonical_pod_acknowledgements(content: str) -> tuple[str, set[str]]:
    """Make CocoaPods acknowledgements stable across hosts and tool formatting."""

    normalized = content.replace("\r\n", "\n").replace("\r", "\n")
    normalized = "\n".join(line.rstrip() for line in normalized.split("\n")).strip()
    matches = list(re.finditer(r"^## ([^\n]+)$", normalized, re.MULTILINE))
    if not matches:
        fail("CocoaPods acknowledgements contain no component sections")

    preamble = [
        line.strip()
        for line in normalized[: matches[0].start()].splitlines()
        if line.strip()
    ]
    if preamble != [POD_ACKNOWLEDGEMENTS_HEADER, POD_ACKNOWLEDGEMENTS_INTRO]:
        fail("CocoaPods acknowledgements have an unexpected preamble")

    sections: dict[str, str] = {}
    for index, match in enumerate(matches):
        name = match.group(1).strip()
        if not name or name in sections:
            fail(f"duplicate or empty CocoaPods acknowledgement heading: {name!r}")
        end = (
            matches[index + 1].start()
            if index + 1 < len(matches)
            else len(normalized)
        )
        body_lines = normalized[match.end() : end].strip().splitlines()
        if index + 1 == len(matches):
            while body_lines and not body_lines[-1].strip():
                body_lines.pop()
            if not body_lines or body_lines[-1].strip() != POD_ACKNOWLEDGEMENTS_FOOTER:
                fail("CocoaPods acknowledgements footer is missing")
            body_lines.pop()
        body = " ".join("\n".join(body_lines).split())
        body = textwrap.fill(
            body,
            width=100,
            break_long_words=False,
            break_on_hyphens=False,
        )
        sections[name] = body

    rendered = [POD_ACKNOWLEDGEMENTS_HEADER, POD_ACKNOWLEDGEMENTS_INTRO]
    for name in sorted(sections, key=str.casefold):
        rendered.extend(["", f"## {name}"])
        if sections[name]:
            rendered.extend(["", sections[name]])
    rendered.extend(["", POD_ACKNOWLEDGEMENTS_FOOTER, ""])
    return "\n".join(rendered), set(sections)


def pod_checksums(path: Path) -> dict[str, str]:
    checksums: dict[str, str] = {}
    section = False
    for line in path.read_text("utf-8").splitlines():
        if line == "SPEC CHECKSUMS:":
            section = True
            continue
        if section and line and not line.startswith(" "):
            break
        if not section:
            continue
        match = re.fullmatch(r"  (.+): ([0-9a-f]{40})", line)
        if match:
            checksums[match.group(1)] = match.group(2)
    if not checksums:
        fail("Podfile.lock contains no SPEC CHECKSUMS")
    return checksums


def generate_cocoapods(
    output: Path,
    lock: Path,
    acknowledgements: Path,
    check: bool,
) -> None:
    if not acknowledgements.is_file():
        fail(
            "CocoaPods acknowledgements are missing; run pod install for the "
            "locked ios/Podfile.lock"
        )
    checksums = pod_checksums(lock)
    source, headings = canonical_pod_acknowledgements(
        acknowledgements.read_text("utf-8", errors="strict")
    )
    missing = sorted(name for name in checksums if name != "Flutter" and name not in headings)
    unknown = sorted(name for name in headings if name not in checksums)
    if missing or unknown:
        fail(
            "CocoaPods acknowledgement coverage differs from Podfile.lock: "
            f"missing={missing}, unknown={unknown}"
        )
    inventory = "\n".join(
        f"- {name} | podspec SHA-1 {digest}"
        for name, digest in sorted(checksums.items(), key=lambda item: item[0].lower())
    )
    content = (
        "LizzieYZY Mobile CocoaPods licenses and notices\n"
        "Generated from the locked Podfile.lock and CocoaPods acknowledgements.\n"
        f"Podfile.lock SHA-256: {sha256_file(lock)}\n\n"
        "Resolved pod inventory\n"
        "----------------------\n"
        f"{inventory}\n\n"
        "Full CocoaPods acknowledgements\n"
        "-------------------------------\n"
        f"{source}"
    )
    write_or_check(output, content, check)
    print(f"CocoaPods legal inventory verified: {len(checksums)} pods -> {output}")


def load_policy(path: Path) -> list[dict[str, Any]]:
    try:
        value = json.loads(path.read_text("utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        fail(f"cannot read native license policy: {error}")
    if not isinstance(value, dict) or value.get("schemaVersion") != 1:
        fail("native license policy must use schemaVersion 1")
    policies = value.get("policies")
    if not isinstance(policies, list) or not policies:
        fail("native license policy contains no policies")
    selectors: set[tuple[str, str]] = set()
    for index, item in enumerate(policies):
        if not isinstance(item, dict):
            fail(f"native license policy entry {index} is not an object")
        required = ("groupPrefix", "license", "licenseUrl")
        if any(not isinstance(item.get(key), str) or not item[key] for key in required):
            fail(f"native license policy entry {index} is incomplete")
        prefix = item["groupPrefix"]
        name_prefix = item.get("namePrefix", "")
        if not isinstance(name_prefix, str):
            fail(f"native license policy entry {index} has an invalid namePrefix")
        selector = (prefix, name_prefix)
        if selector in selectors:
            fail(f"duplicate native license selector: {selector}")
        selectors.add(selector)
    return sorted(
        policies,
        key=lambda item: len(item["groupPrefix"]) + len(item.get("namePrefix", "")),
        reverse=True,
    )


def policy_for(
    group: str, name: str, policies: list[dict[str, Any]]
) -> dict[str, Any]:
    matches = [
        item
        for item in policies
        if group.startswith(item["groupPrefix"])
        and name.startswith(item.get("namePrefix", ""))
    ]
    if not matches:
        fail(f"unreviewed Maven group in resolved graph: {group}")
    selected = matches[0]
    equally_specific = [
        item
        for item in matches
        if len(item["groupPrefix"]) + len(item.get("namePrefix", ""))
        == len(selected["groupPrefix"]) + len(selected.get("namePrefix", ""))
    ]
    if len(equally_specific) != 1:
        fail(f"ambiguous Maven license policy for group: {group}")
    return selected


def module_files(cache: Path, group: str, name: str, version: str) -> list[Path]:
    root = cache / group / name / version
    if not root.is_dir():
        return []
    expected_stem = f"{name}-{version}"
    return sorted(
        (
            path
            for path in root.glob("*/*")
            if path.is_file()
            and path.suffix.lower() in ARCHIVE_SUFFIXES | METADATA_SUFFIXES
            # Classifier artifacts (sources, javadoc, lint, samples) are not
            # members of releaseRuntimeClasspath and make cache scans depend
            # on unrelated local/CI activity. Only the coordinate's primary
            # payload and metadata are legal release evidence.
            and path.stem == expected_stem
        ),
        key=lambda path: (path.suffix, path.name, sha256_file(path)),
    )


def verification_artifacts(path: Path) -> dict[tuple[str, str, str], list[dict[str, str]]]:
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError) as error:
        fail(f"cannot read Gradle verification metadata: {error}")
    namespace = "{https://schema.gradle.org/dependency-verification}"
    result: dict[tuple[str, str, str], list[dict[str, str]]] = {}
    for component in root.findall(f"{namespace}components/{namespace}component"):
        coordinate = (
            component.get("group", ""),
            component.get("name", ""),
            component.get("version", ""),
        )
        artifacts = []
        for artifact in component.findall(namespace + "artifact"):
            name = artifact.get("name", "")
            digest_nodes = artifact.findall(namespace + "sha256")
            if not name or not digest_nodes:
                fail(f"incomplete Gradle artifact hash for {coordinate}")
            digests = {node.get("value", "") for node in digest_nodes}
            if len(digests) != 1:
                fail(f"ambiguous Gradle artifact hashes for {coordinate} {name}")
            digest = next(iter(digests))
            if re.fullmatch(r"[0-9a-f]{64}", digest) is None:
                fail(f"invalid Gradle artifact SHA-256 for {coordinate} {name}")
            artifacts.append(
                {
                    "file": name,
                    "sha256": digest,
                    "kind": Path(name).suffix.lower().lstrip(".") or "metadata",
                }
            )
        if coordinate in result:
            fail(f"duplicate Gradle verification component: {coordinate}")
        result[coordinate] = sorted(artifacts, key=lambda item: item["file"])
    return result


def legal_entries(path: Path) -> list[tuple[str, bytes]]:
    if path.suffix.lower() not in ARCHIVE_SUFFIXES:
        return []
    try:
        with zipfile.ZipFile(path) as archive:
            result = []
            for name in sorted(archive.namelist()):
                if name.endswith("/") or LEGAL_NAME.search(name) is None:
                    continue
                result.append((name, archive.read(name)))
            return result
    except zipfile.BadZipFile as error:
        fail(f"invalid resolved Maven archive {path.name}: {error}")


def pom_licenses(path: Path) -> list[dict[str, str]]:
    if path.suffix.lower() != ".pom":
        return []
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as error:
        fail(f"invalid Maven POM {path.name}: {error}")
    result: list[dict[str, str]] = []
    for element in root.iter():
        if element.tag.rsplit("}", 1)[-1] != "license":
            continue
        entry: dict[str, str] = {}
        for child in element:
            key = child.tag.rsplit("}", 1)[-1]
            if key in {"name", "url"} and child.text:
                entry[key] = child.text.strip()
        if entry:
            result.append(entry)
    return result


def verify_pom_licenses(
    coordinate: str, policy: dict[str, Any], declarations: list[dict[str, str]]
) -> None:
    if not declarations:
        return
    material = " ".join(
        f"{entry.get('name', '')} {entry.get('url', '')}" for entry in declarations
    ).lower()
    license_id = policy["license"]
    compatible = False
    if license_id == "Apache-2.0":
        compatible = "apache" in material and (
            "2.0" in material or "license-2.0" in material
        )
    elif license_id == "BSD-3-Clause":
        compatible = "bsd" in material or "flutter/blob/master/license" in material
    else:
        compatible = policy["licenseUrl"].lower() in material
    if not compatible:
        fail(
            f"{coordinate} POM license differs from reviewed policy "
            f"{license_id}: {declarations}"
        )


def flutter_license() -> str:
    roots = sbom.package_roots()
    flutter_root = roots.get("flutter")
    if flutter_root is None:
        fail("Flutter package root is missing from package_config.json")
    path = flutter_root.parents[1] / "LICENSE"
    if not path.is_file():
        fail("Flutter SDK LICENSE is missing")
    return path.read_text("utf-8", errors="strict").rstrip() + "\n"


def canonical_apache_text(texts: dict[str, bytes]) -> tuple[str, bytes]:
    for digest, data in sorted(texts.items()):
        normalized = " ".join(data.decode("utf-8", errors="replace").lower().split())
        if "apache license" in normalized and "version 2.0" in normalized:
            return digest, data
    fail("resolved Maven archives contain no complete Apache-2.0 license text")


def generate_maven(
    output: Path,
    report: Path,
    policy_path: Path,
    cache: Path,
    verification_metadata: Path,
    manifest_output: Path | None,
    check: bool,
) -> None:
    policies = load_policy(policy_path)
    modules = sbom.parse_android_report(report)
    verified_artifacts = verification_artifacts(verification_metadata)
    graph_sha256 = sha256_bytes(
        ("\n".join(module["purl"] for module in modules) + "\n").encode("utf-8")
    )
    notices: dict[str, bytes] = {}
    notice_sources: dict[str, set[str]] = {}
    manifest_components: list[dict[str, Any]] = []
    inventory_lines: list[str] = []
    applied_licenses: set[str] = set()

    for module in modules:
        group = module["group"]
        name = module["name"]
        version = module["version"]
        coordinate = f"{group}:{name}:{version}"
        policy = policy_for(group, name, policies)
        applied_licenses.add(policy["license"])
        files = module_files(cache, group, name, version)
        coordinate_key = (group, name, version)
        artifact_entries = verified_artifacts.get(coordinate_key)
        if not artifact_entries:
            fail(f"resolved Maven module has no Gradle SHA-256 lock: {coordinate}")
        verified_by_name = {item["file"]: item["sha256"] for item in artifact_entries}
        component_notice_ids: set[str] = set()
        declared_licenses: list[dict[str, str]] = []
        for path in files:
            digest = sha256_file(path)
            expected_digest = verified_by_name.get(path.name)
            if expected_digest is None:
                continue
            if expected_digest != digest:
                fail(f"cached artifact differs from Gradle SHA-256 lock: {coordinate} {path.name}")
            declared_licenses.extend(pom_licenses(path))
            for entry_name, data in legal_entries(path):
                notice_digest = sha256_bytes(data)
                notices.setdefault(notice_digest, data)
                notice_sources.setdefault(notice_digest, set()).add(
                    f"{coordinate}!/{entry_name}"
                )
                component_notice_ids.add(notice_digest)
        verify_pom_licenses(coordinate, policy, declared_licenses)
        if policy.get("requireEmbeddedNotices") is True and not component_notice_ids:
            fail(f"{coordinate} is required to preserve embedded notices, but none exist")
        resolution = "gradle-sha256-lock"
        notice_short = ",".join(sorted(item[:12] for item in component_notice_ids)) or "policy"
        inventory_lines.append(
            f"- {coordinate} | {policy['license']} | {policy['licenseUrl']} | "
            f"{resolution} | notices {notice_short}"
        )
        manifest_components.append(
            {
                "purl": module["purl"],
                "coordinate": coordinate,
                "license": policy["license"],
                "licenseUrl": policy["licenseUrl"],
                "artifacts": artifact_entries,
                "noticeSha256": sorted(component_notice_ids),
                "pomLicenses": declared_licenses,
                "resolution": resolution,
            }
        )

    apache_digest, apache_data = canonical_apache_text(notices)
    flutter_text = flutter_license()
    synthetic_texts: list[tuple[str, str, str]] = []
    if "Apache-2.0" in applied_licenses:
        synthetic_texts.append(
            ("Apache-2.0", apache_digest, apache_data.decode("utf-8", errors="replace"))
        )
    if "BSD-3-Clause" in applied_licenses:
        synthetic_texts.append(
            ("Flutter SDK BSD-3-Clause", sha256_bytes(flutter_text.encode()), flutter_text)
        )

    chunks = [
        "LizzieYZY Mobile resolved Maven licenses and notices\n",
        "Generated from the exact Gradle releaseRuntimeClasspath graph.\n",
        f"Resolved Maven graph SHA-256: {graph_sha256}\n",
        f"License policy SHA-256: {sha256_file(policy_path)}\n\n",
        "Resolved Maven component inventory\n",
        "-----------------------------------\n",
        "\n".join(inventory_lines) + "\n\n",
        "Reviewed license terms\n",
        "----------------------\n",
        "LicenseRef-Android-SDK-Terms: https://developer.android.com/studio/terms.html\n",
        "LicenseRef-ML-Kit-Terms: https://developers.google.com/ml-kit/terms\n",
        "The linked vendor terms are authoritative and may be updated by their publisher.\n",
    ]
    emitted: set[str] = set()
    for title, digest, text in synthetic_texts:
        if digest in emitted:
            continue
        emitted.add(digest)
        chunks.extend(
            [
                "\n" + "=" * 78 + "\n",
                f"{title} | SHA-256 {digest}\n",
                "=" * 78 + "\n",
                text.rstrip() + "\n",
            ]
        )
    for digest, data in sorted(notices.items()):
        if digest in emitted:
            continue
        emitted.add(digest)
        sources = sorted(notice_sources[digest])
        chunks.extend(
            [
                "\n" + "=" * 78 + "\n",
                f"Embedded Maven legal text | SHA-256 {digest}\n",
                "Sources: " + "; ".join(sources) + "\n",
                "=" * 78 + "\n",
                data.decode("utf-8", errors="replace").rstrip() + "\n",
            ]
        )
    content = "".join(chunks)
    write_or_check(output, content, check)

    manifest = {
        "schemaVersion": 1,
        "resolvedGraphSha256": graph_sha256,
        "licensePolicySha256": sha256_file(policy_path),
        "gradleVerificationSha256": sha256_file(verification_metadata),
        "components": manifest_components,
        "legalTexts": [
            {
                "sha256": digest,
                "sources": sorted(notice_sources[digest]),
            }
            for digest in sorted(notices)
        ],
    }
    if manifest_output is not None:
        manifest_output.parent.mkdir(parents=True, exist_ok=True)
        manifest_output.write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", "utf-8"
        )
    print(
        f"Maven legal inventory verified: {len(modules)} modules, "
        f"{len(notices)} unique embedded legal texts -> {output}"
    )


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__)
    commands = root.add_subparsers(dest="command", required=True)
    cocoa = commands.add_parser("cocoapods")
    cocoa.add_argument("--output", type=Path, default=COCOAPODS_ASSET)
    cocoa.add_argument("--pod-lock", type=Path, default=POD_LOCK)
    cocoa.add_argument("--acknowledgements", type=Path, default=POD_ACKNOWLEDGEMENTS)
    cocoa.add_argument("--check", action="store_true")
    maven = commands.add_parser("maven")
    maven.add_argument("--output", type=Path, default=MAVEN_ASSET)
    maven.add_argument("--android-report", type=Path, required=True)
    maven.add_argument("--policy", type=Path, default=POLICY)
    maven.add_argument("--gradle-cache", type=Path, default=GRADLE_CACHE)
    maven.add_argument(
        "--verification-metadata", type=Path, default=GRADLE_VERIFICATION
    )
    maven.add_argument("--manifest-output", type=Path)
    maven.add_argument("--check", action="store_true")
    return root


def main() -> int:
    args = parser().parse_args()
    try:
        if args.command == "cocoapods":
            generate_cocoapods(
                args.output, args.pod_lock, args.acknowledgements, args.check
            )
        else:
            generate_maven(
                args.output,
                args.android_report,
                args.policy,
                args.gradle_cache,
                args.verification_metadata,
                args.manifest_output,
                args.check,
            )
    except (OSError, UnicodeError, sbom.SbomError) as error:
        print(f"native license generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
